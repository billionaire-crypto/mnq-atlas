"""Stage 2 tests-first witnesses for the canonical session-availability model.

Written BEFORE `mnq_lab/spine/availability.py` exists (D32 repair, Stage 2).
Every test therefore fails at import until Stage 3 implements the module, so the
whole module is marked ``xfail(strict=True)``: when the implementation lands the
strict marker turns these into failures and forces the marker's removal. A
skipped test would be a check that cannot fail, which this project forbids.

Expected values are literal and derived by hand from the declared boundary
convention. None is generated by calling the implementation.

Time is expressed in America/Chicago minutes from midnight:
    08:30 -> 510      11:56 -> 716      15:00 -> 900
    12:00 -> 720      14:00 -> 840

NOTE ON THE FOUR MARCH 2020 SESSIONS. Authoritative CME futures interruption
boundaries are NOT established (design doc section 10). No test here registers an
interruption on 20200309/0312/0316/0318. Interruption behaviour is pinned on a
clearly synthetic session id (29990101) so that nothing in this file can be
mistaken for a registered historical fact.
"""

from __future__ import annotations

import pytest

pytestmark = pytest.mark.xfail(
    strict=True,
    reason="Stage 3 implements mnq_lab/spine/availability.py; Stage 3 removes this marker",
)

CT = "America/Chicago"
SOURCE = "SYNTHETIC-TEST-NOT-A-REGISTERED-SOURCE"

RTH_OPEN = 510
RTH_CLOSE_FULL = 900
EARLY_CLOSE = 720

FULL_SESSION = 20200102
EARLY_SESSION = 20191129
NO_RTH_SESSION = 20210402
INTERRUPTED_SESSION = 29990101
UNKNOWN_SESSION = 29990102

TRUNCATION_SESSIONS = (20200228, 20200630)
MARCH_SESSIONS = (20200309, 20200312, 20200316, 20200318)


def _mod():
    """Import inside the test so collection succeeds before Stage 3."""
    from mnq_lab.spine import availability

    return availability


def _schedule(mod, session_id, *, status="full_rth", close=RTH_CLOSE_FULL,
              open_ct=RTH_OPEN, interruptions=(), timezone=CT):
    return mod.SessionSchedule(
        session_id=session_id,
        scheduled_rth_open_ct=open_ct,
        scheduled_rth_close_ct=close,
        scheduled_rth_status=status,
        structural_interruptions=tuple(interruptions),
        timezone=timezone,
        calendar_version="mnq-cme-equity-index-calendar-v1",
        calendar_sha256="b86e112c16112bf11a6a548ca8b3f21d28a08f90442b4dde84098f9d3f6eb069",
        interruption_source_id=None,
    )


def _interruption(mod, start, end, source=SOURCE):
    return mod.StructuralInterruption(
        start_ct_minute=start,
        end_ct_minute=end,
        reason="registered_interruption",
        source_id=source,
    )


def _table(mod, *schedules, exclusions=()):
    return mod.build_session_schedule_table(schedules, exclusions=exclusions)


def _decide(mod, table, session_id, tau, horizon):
    return mod.outcome_window_structurally_available(
        session_id=session_id,
        tau_ct_minute=tau,
        horizon_minutes=horizon,
        schedule_table=table,
    )


