# --------------------------------------------------------------------------
# 13-15: named mutants. Each must DISAGREE with the canonical answer on its
# witness, proving the witness discriminates rather than merely passing.
# --------------------------------------------------------------------------


def _mutant_fixed_1500(session_id, tau, horizon, table):
    """Mutant 13: ignores the schedule, uses a fixed 15:00 close."""
    return tau + horizon <= RTH_CLOSE_FULL


def _mutant_infer_close_from_last_bar(session_id, tau, horizon, observed_last_end):
    """Mutant 14: derives the close from observed bars instead of the schedule."""
    return tau + horizon <= observed_last_end


def _mutant_exclude_whole_session(session_id, tau, horizon, table):
    """Mutant 15: excludes the entire session when any interruption exists."""
    return not table.lookup(session_id).structural_interruptions


def test_13_fixed_1500_mutant_fails_the_early_close_witness():
    mod = _mod()
    table = _table(mod, _schedule(mod, EARLY_SESSION, status="shortened_rth",
                                  close=EARLY_CLOSE))
    canonical = _decide(mod, table, EARLY_SESSION, 840, 15).available
    assert canonical is False
    assert _mutant_fixed_1500(EARLY_SESSION, 840, 15, table) is True
    assert canonical != _mutant_fixed_1500(EARLY_SESSION, 840, 15, table)


def test_14_missing_bar_inference_mutant_fails_on_an_unresolved_truncation():
    mod = _mod()
    table = _table(mod, _schedule(mod, 20200228))
    # 20200228 is a REGULAR full_rth session whose observed bars stop at 10:00.
    canonical = _decide(mod, table, 20200228, 660, 60).available
    assert canonical is True
    inferred = _mutant_infer_close_from_last_bar(20200228, 660, 60, 600)
    assert inferred is False
    assert canonical != inferred


def test_15_whole_session_exclusion_mutant_kills_a_valid_post_resumption_window():
    mod = _mod()
    table = _interrupted(mod)
    canonical = _decide(mod, table, INTERRUPTED_SESSION, 800, 60).available
    assert canonical is True
    assert _mutant_exclude_whole_session(INTERRUPTED_SESSION, 800, 60, table) is False
    assert canonical != _mutant_exclude_whole_session(
        INTERRUPTED_SESSION, 800, 60, table
    )
